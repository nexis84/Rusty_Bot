#!/usr/bin/env node
/* Build market/skin-ships.js: ship typeID -> [skin license typeIDs].
 *
 * Sources:
 *   sde/skinLicenses.jsonl  license typeID -> skinID
 *   sde/skins.jsonl         skinID -> ship typeIDs + internal name
 *   market/items_database.js  only keep skins/ships currently in the market
 *
 * Run after generate_items_db.py, e.g.:
 *   node scripts/build-skin-ships.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SDE = path.join(ROOT, 'sde');
const DB = path.join(ROOT, 'market', 'items_database.js');
const OUT = path.join(ROOT, 'market', 'skin-ships.js');

async function* jsonl(file) {
  const rl = readline.createInterface({
    input: fs.createReadStream(file, { encoding: 'utf8' }),
    crlfDelay: Infinity,
  });
  for await (const line of rl) {
    const text = line.trim();
    if (text) yield JSON.parse(text);
  }
}

function loadMarket() {
  const context = {};
  vm.createContext(context);
  vm.runInContext(
    fs.readFileSync(DB, 'utf8') + '\n;globalThis.__market = AllMarketItems;',
    context,
  );
  return context.__market;
}

async function main() {
  for (const file of ['skinLicenses.jsonl', 'skins.jsonl']) {
    const full = path.join(SDE, file);
    if (!fs.existsSync(full)) throw new Error(`missing SDE file: ${full}`);
  }

  const market = loadMarket();
  const shipIds = new Set(market.ships.items.map(item => item.id));
  const skinItems = new Map(market.skins.items.map(item => [item.id, item.name]));

  const skins = new Map();
  const skinsByName = new Map();
  for await (const skin of jsonl(path.join(SDE, 'skins.jsonl'))) {
    skins.set(skin._key, skin);
    const name = (skin.internalName || '').trim();
    if (name) skinsByName.set(name, skin);
  }

  const shipToSkins = new Map();
  const mappedSkins = new Set();

  function addSkin(skinTypeId, shipTypeIds) {
    if (!skinItems.has(skinTypeId)) return false;
    let added = false;
    for (const shipTypeId of shipTypeIds || []) {
      if (!shipIds.has(shipTypeId)) continue;
      if (!shipToSkins.has(shipTypeId)) shipToSkins.set(shipTypeId, new Set());
      shipToSkins.get(shipTypeId).add(skinTypeId);
      added = true;
    }
    if (added) mappedSkins.add(skinTypeId);
    return added;
  }

  // Primary mapping: market license -> skin record -> ship types.
  let licenseRows = 0;
  for await (const license of jsonl(path.join(SDE, 'skinLicenses.jsonl'))) {
    licenseRows++;
    const skinTypeId = license.licenseTypeID ?? license._key;
    const skin = skins.get(license.skinID);
    if (skin) addSkin(skinTypeId, skin.types);
  }

  // Some newly added skins have a license but no skinLicenses row yet. Match
  // the market name to the skins.jsonl internal name.
  for (const [skinTypeId, name] of skinItems) {
    if (mappedSkins.has(skinTypeId)) continue;
    const base = name.replace(/\s+SKIN$/i, '').trim();
    const skin = skinsByName.get(base);
    if (skin) addSkin(skinTypeId, skin.types);
  }

  // Last resort: the skin name starts with its ship's name. Sort by name
  // length so "Omen Navy Issue" wins over "Omen".
  const shipNames = [...market.ships.items].sort((a, b) => b.name.length - a.name.length);
  for (const [skinTypeId, name] of skinItems) {
    if (mappedSkins.has(skinTypeId)) continue;
    const base = name.replace(/\s+SKIN$/i, '').trim();
    const ship = shipNames.find(candidate =>
      base === candidate.name || base.startsWith(candidate.name + ' '),
    );
    if (ship) addSkin(skinTypeId, [ship.id]);
  }

  const output = {};
  for (const shipTypeId of [...shipToSkins.keys()].sort((a, b) => a - b)) {
    output[shipTypeId] = [...shipToSkins.get(shipTypeId)].sort((a, b) => a - b);
  }

  const lines = [
    '// Auto-generated by scripts/build-skin-ships.mjs - do not edit by hand.',
    `// ${mappedSkins.size} skins across ${Object.keys(output).length} ships.`,
    `window.SkinShips = ${JSON.stringify(output)};`,
    '',
  ];
  fs.writeFileSync(OUT, lines.join('\n'), 'utf8');

  const unmapped = [...skinItems.keys()].filter(id => !mappedSkins.has(id));
  const max = Math.max(0, ...Object.values(output).map(list => list.length));
  console.log(`license rows:      ${licenseRows}`);
  console.log(`market skins:      ${skinItems.size}`);
  console.log(`mapped skins:      ${mappedSkins.size}`);
  console.log(`ships with skins:  ${Object.keys(output).length}`);
  console.log(`largest ship set:  ${max}`);
  if (unmapped.length) {
    console.log(`unmapped skins:    ${unmapped.length}`);
    for (const id of unmapped.slice(0, 10)) console.log(`  ${id}: ${skinItems.get(id)}`);
  }
  console.log(`written:           ${OUT}`);
  if (unmapped.length) process.exitCode = 1;
}

main().catch(error => {
  console.error(error.message);
  process.exit(1);
});
